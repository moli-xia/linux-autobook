#!/usr/bin/env bash
set -Eeuo pipefail

INSTALL_DIR="/opt/autobook-linux"
CONFIG_DIR="/etc/linux-autobook"
ADMIN_PORT="8766"
ADMIN_BIND="0.0.0.0"
PUBLIC_HOST=""
DOMAIN=""
ACME_EMAIL=""
ROLE=""
ACTION=""
GATEWAY_URL=""
GATEWAY_TOKEN=""
GATEWAY_CA_FILE=""
PURGE=0
NON_INTERACTIVE=0
REPO_URL_OVERRIDE="${AUTOBOOK_REPO_URL:-}"
REPO_BRANCH_OVERRIDE="${AUTOBOOK_BRANCH:-}"
REPO_URL="${REPO_URL_OVERRIDE:-https://github.com/moli-xia/linux-autobook.git}"
REPO_BRANCH="${REPO_BRANCH_OVERRIDE:-main}"
SOURCE_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"

usage() {
  cat <<'EOF'
Usage: sudo bash install.sh [options]

Without options an interactive Chinese menu is displayed.

  --action install|update|status|uninstall
  --role all|gateway|worker
  --domain DOMAIN              Obtain an auto-renewed Let's Encrypt certificate
  --acme-email EMAIL           Optional certificate expiry email
  --public-host HOST           Link/certificate host when no domain is used
  --admin-port PORT
  --admin-bind ADDRESS
  --gateway-url HTTPS_URL      Worker-only central gateway URL
  --gateway-token TOKEN        Shared gateway token
  --gateway-ca-file PATH       Private/self-signed gateway CA path
  --install-dir PATH
  --purge                      Uninstall without creating a config/data backup
  --non-interactive
EOF
}

while (($#)); do
  case "$1" in
    --action) ACTION="${2:-}"; shift 2 ;;
    --role) ROLE="${2:-}"; shift 2 ;;
    --domain) DOMAIN="${2:-}"; shift 2 ;;
    --acme-email) ACME_EMAIL="${2:-}"; shift 2 ;;
    --public-host) PUBLIC_HOST="${2:-}"; shift 2 ;;
    --admin-port) ADMIN_PORT="${2:-}"; shift 2 ;;
    --admin-bind) ADMIN_BIND="${2:-}"; shift 2 ;;
    --gateway-url) GATEWAY_URL="${2:-}"; shift 2 ;;
    --gateway-token) GATEWAY_TOKEN="${2:-}"; shift 2 ;;
    --gateway-ca-file) GATEWAY_CA_FILE="${2:-}"; shift 2 ;;
    --install-dir) INSTALL_DIR="${2:-}"; shift 2 ;;
    --purge) PURGE=1; shift ;;
    --non-interactive) NON_INTERACTIVE=1; shift ;;
    -h|--help) usage; exit 0 ;;
    *) echo "Unknown argument: $1" >&2; usage; exit 2 ;;
  esac
done

if [[ "${EUID}" -ne 0 ]]; then
  echo "Please run as root: sudo bash install.sh" >&2
  exit 1
fi

validate_common() {
  if [[ ! "$ADMIN_PORT" =~ ^[0-9]{1,5}$ ]] || ((ADMIN_PORT < 1 || ADMIN_PORT > 65535)); then
    echo "Invalid admin port: $ADMIN_PORT" >&2; exit 2
  fi
  if [[ ! "$INSTALL_DIR" =~ ^/[A-Za-z0-9._/-]+$ || "$INSTALL_DIR" == "/" ]]; then
    echo "Invalid install directory: $INSTALL_DIR" >&2; exit 2
  fi
  if [[ ! "$CONFIG_DIR" =~ ^/[A-Za-z0-9._/-]+$ || "$CONFIG_DIR" == "/" ]]; then
    echo "Invalid config directory: $CONFIG_DIR" >&2; exit 2
  fi
  if [[ ! "$ADMIN_BIND" =~ ^[A-Za-z0-9.:-]+$ ]]; then
    echo "Invalid admin bind address: $ADMIN_BIND" >&2; exit 2
  fi
  if [[ -n "$DOMAIN" && ! "$DOMAIN" =~ ^[A-Za-z0-9]([A-Za-z0-9.-]*[A-Za-z0-9])?$ ]]; then
    echo "Invalid domain: $DOMAIN" >&2; exit 2
  fi
  if [[ -n "$PUBLIC_HOST" && ! "$PUBLIC_HOST" =~ ^[A-Za-z0-9._:-]+$ ]]; then
    echo "Invalid public host: $PUBLIC_HOST" >&2; exit 2
  fi
  if [[ -n "$GATEWAY_URL" ]] \
    && [[ ! "$GATEWAY_URL" =~ ^https://[A-Za-z0-9._:-]+/?$ ]] \
    && [[ ! "$GATEWAY_URL" =~ ^https://\[[0-9A-Fa-f:]+\](:[0-9]+)?/?$ ]]; then
      echo "Gateway URL must be a simple HTTPS origin: $GATEWAY_URL" >&2; exit 2
  fi
  if [[ -n "$GATEWAY_TOKEN" && ! "$GATEWAY_TOKEN" =~ ^[A-Za-z0-9._~-]{16,256}$ ]]; then
    echo "Gateway token must be 16-256 safe characters" >&2; exit 2
  fi
}

choose_action() {
  echo
  echo "========== linux-autobook 管理菜单 =========="
  echo "1) 安装或重新配置"
  echo "2) 更新程序（保留配置和数据）"
  echo "3) 查看安装状态"
  echo "4) 卸载"
  echo "0) 退出"
  read -r -p "请选择 [1]: " choice
  case "${choice:-1}" in
    1) ACTION="install" ;; 2) ACTION="update" ;; 3) ACTION="status" ;;
    4) ACTION="uninstall" ;; 0) exit 0 ;; *) echo "无效选项" >&2; exit 2 ;;
  esac
}

choose_role() {
  echo
  echo "选择本机角色："
  echo "1) 网关 + Worker（单机，推荐首次部署）"
  echo "2) 仅百度下载网关（中心节点）"
  echo "3) 仅 Worker（计算节点，可部署多台）"
  read -r -p "请选择 [1]: " choice
  case "${choice:-1}" in
    1) ROLE="all" ;; 2) ROLE="gateway" ;; 3) ROLE="worker" ;;
    *) echo "无效角色" >&2; exit 2 ;;
  esac
}

load_install_state() {
  local state="/etc/linux-autobook/install.env"
  if [[ -r "$state" ]]; then
    # Generated by this installer and writable only by root.
    # shellcheck disable=SC1090
    source "$state"
    INSTALL_DIR="${INSTALL_DIR:-/opt/autobook-linux}"
    CONFIG_DIR="${CONFIG_DIR:-/etc/linux-autobook}"
  fi
}

show_status() {
  load_install_state
  echo "Install directory: $INSTALL_DIR"
  echo "Config directory:  $CONFIG_DIR"
  if [[ -r "$CONFIG_DIR/install.env" ]]; then
    echo "Role:              ${INSTALL_ROLE:-unknown}"
    echo "TLS mode:          ${TLS_MODE:-unknown}"
    echo "Public host:       ${PUBLIC_HOST:-unknown}"
  else
    echo "State:             not installed"
  fi
  for unit in autobook-admin autobook-gateway autobook-worker; do
    if systemctl cat "$unit.service" >/dev/null 2>&1; then
      state="$(systemctl is-active "$unit.service" 2>/dev/null || true)"
    else
      state="not-installed"
    fi
    printf '%-20s %s\n' "$unit" "$state"
  done
}

uninstall_app() {
  load_install_state
  validate_common
  if ((NON_INTERACTIVE == 0)); then
    echo "将停止服务并删除 $INSTALL_DIR 与 $CONFIG_DIR。"
    if ((PURGE == 0)); then
      echo "配置和 runtime 数据会先保存到 /var/backups/linux-autobook。"
    fi
    read -r -p "确认卸载？输入 YES: " answer
    [[ "$answer" == "YES" ]] || { echo "已取消"; exit 0; }
  fi

  for unit in autobook-admin.service autobook-gateway.service autobook-worker.service; do
    systemctl disable --now "$unit" 2>/dev/null || true
  done
  local backup=""
  if ((PURGE == 0)) && { [[ -d "$CONFIG_DIR" ]] || [[ -d "$INSTALL_DIR/runtime" ]]; }; then
    install -d -m 700 /var/backups/linux-autobook
    backup="/var/backups/linux-autobook/backup-$(date +%Y%m%d-%H%M%S).tar.gz"
    local items=()
    [[ -d "$CONFIG_DIR" ]] && items+=("${CONFIG_DIR#/}")
    [[ -d "$INSTALL_DIR/runtime" ]] && items+=("${INSTALL_DIR#/}/runtime")
    tar -C / -czf "$backup" "${items[@]}"
    chmod 600 "$backup"
  fi
  rm -f /etc/systemd/system/autobook-admin.service /etc/systemd/system/autobook-gateway.service /etc/systemd/system/autobook-worker.service
  rm -f /etc/letsencrypt/renewal-hooks/deploy/autobook-cert-deploy /usr/local/sbin/autobook-cert-deploy
  rm -rf -- "$INSTALL_DIR" "$CONFIG_DIR"
  systemctl daemon-reload
  systemctl reset-failed
  echo "linux-autobook 已卸载。"
  [[ -n "$backup" ]] && echo "配置/数据备份: $backup"
}

perform_update() {
  load_install_state
  [[ -z "$REPO_URL_OVERRIDE" ]] || REPO_URL="$REPO_URL_OVERRIDE"
  [[ -z "$REPO_BRANCH_OVERRIDE" ]] || REPO_BRANCH="$REPO_BRANCH_OVERRIDE"
  if [[ ! -r "$CONFIG_DIR/install.env" ]]; then
    echo "No existing installation found; use Install first." >&2
    exit 1
  fi
  local update_role="${INSTALL_ROLE:-all}"
  local update_domain="${TLS_DOMAIN:-}"
  local update_host="${PUBLIC_HOST:-}"
  local update_port="${ADMIN_PORT:-8766}"
  local tmp_dir
  tmp_dir="$(mktemp -d /tmp/linux-autobook-update.XXXXXX)"
  trap '[[ -n "${tmp_dir:-}" && "$tmp_dir" == /tmp/linux-autobook-update.* ]] && rm -rf -- "$tmp_dir"' EXIT
  git clone --depth 1 --branch "$REPO_BRANCH" "$REPO_URL" "$tmp_dir/source"
  bash "$tmp_dir/source/install.sh" --action install --role "$update_role" \
    --install-dir "$INSTALL_DIR" --admin-port "$update_port" \
    --public-host "$update_host" --domain "$update_domain" --non-interactive
  echo "Update completed from $REPO_URL ($REPO_BRANCH)."
}

if [[ -z "$ACTION" ]]; then
  if ((NON_INTERACTIVE == 0)) && [[ -t 0 ]]; then choose_action; else ACTION="install"; fi
fi
case "$ACTION" in
  status) show_status; exit 0 ;;
  uninstall) uninstall_app; exit 0 ;;
  update) perform_update; exit 0 ;;
  install) ;;
  *) echo "Invalid action: $ACTION" >&2; exit 2 ;;
esac

if [[ -z "$ROLE" ]]; then
  if ((NON_INTERACTIVE == 0)) && [[ -t 0 ]]; then choose_role; else ROLE="all"; fi
fi
if [[ "$ROLE" != "all" && "$ROLE" != "gateway" && "$ROLE" != "worker" ]]; then
  echo "Invalid role: $ROLE" >&2; exit 2
