set_env() {
  local file="$1" key="$2" value="$3" tmp
  [[ "$value" != *$'\n'* && "$value" != *$'\r'* ]] || { echo "Invalid newline in $key" >&2; exit 2; }
  tmp="${file}.tmp.$$"
  if [[ -f "$file" ]]; then
    awk -v key="$key" -v line="$key=$value" 'BEGIN{done=0} $0 ~ "^" key "=" {if(!done){print line; done=1}; next} {print} END{if(!done) print line}' "$file" > "$tmp"
  else
    printf '%s=%s\n' "$key" "$value" > "$tmp"
  fi
  install -m 600 -o root -g root "$tmp" "$file"
  rm -f "$tmp"
}

ensure_env() {
  local file="$1" key="$2" value="$3"
  grep -q "^${key}=" "$file" 2>/dev/null || set_env "$file" "$key" "$value"
}

read_env_value() {
  local file="$1" key="$2"
  sed -n "s/^${key}=//p" "$file" 2>/dev/null | tail -n1 | sed 's/^"//;s/"$//' || true
}

write_state() {
  local tls_mode="$1"
  {
    printf 'INSTALL_DIR=%q\n' "$INSTALL_DIR"
