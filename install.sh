  fi
fi
validate_common

if [[ ! -f "$SOURCE_DIR/run_admin.py" || ! -d "$SOURCE_DIR/autobook_linux" ]]; then
  echo "install.sh must be run from a complete linux-autobook checkout." >&2
  exit 1
