    printf 'INSTALL_ROLE=%q\n' "$ROLE"
    printf 'PUBLIC_HOST=%q\n' "$PUBLIC_HOST"
    printf 'TLS_MODE=%q\n' "$tls_mode"
    printf 'TLS_DOMAIN=%q\n' "$DOMAIN"
    printf 'ADMIN_PORT=%q\n' "$ADMIN_PORT"
    printf 'REPO_URL=%q\n' "$REPO_URL"
    printf 'REPO_BRANCH=%q\n' "$REPO_BRANCH"
  } > "$CONFIG_DIR/install.env"
  chmod 600 "$CONFIG_DIR/install.env"
}

