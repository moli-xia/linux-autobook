    read -r -p "中心网关地址（例如 https://gateway.example.com:8765）: " input_gateway
    GATEWAY_URL="${input_gateway:-$GATEWAY_URL}"
    read -r -s -p "中心网关共享令牌（也可稍后在面板填写）: " input_token; echo
    GATEWAY_TOKEN="${input_token:-$GATEWAY_TOKEN}"
    read -r -p "自签名网关 CA 文件路径（公有证书留空）: " input_ca
