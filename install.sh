if ((NON_INTERACTIVE == 0)) && [[ -t 0 ]]; then
  read -r -p "管理域名（已解析到本机则自动申请免费证书，留空使用自签名）: " input_domain
  DOMAIN="${input_domain:-$DOMAIN}"
  if [[ -n "$DOMAIN" ]]; then
    read -r -p "Let's Encrypt 通知邮箱（可留空）: " input_email
    ACME_EMAIL="${input_email:-$ACME_EMAIL}"
  else
    read -r -p "面板显示的公网 IP/主机名（留空自动检测）: " input_host
    PUBLIC_HOST="${input_host:-$PUBLIC_HOST}"
  fi
  read -r -p "管理面板端口 [$ADMIN_PORT]: " input_port
  ADMIN_PORT="${input_port:-$ADMIN_PORT}"
