if command -v apt-get >/dev/null 2>&1; then
  apt-get update
  apt-get install -y git curl python3 python3-venv python3-pip p7zip-full aria2 openssl ca-certificates
  [[ -z "$DOMAIN" ]] || apt-get install -y certbot
