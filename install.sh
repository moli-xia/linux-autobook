echo "[5/8] Creating HTTPS certificates..."
if [[ "$PUBLIC_HOST" =~ ^[0-9]+(\.[0-9]+){3}$ || "$PUBLIC_HOST" == *:* ]]; then PUBLIC_SAN="IP:${PUBLIC_HOST}"; else PUBLIC_SAN="DNS:${PUBLIC_HOST}"; fi
generate_self_signed() {
  local cert="$1" key="$2" owner="$3" group="$4"
  local valid=0
  if [[ -s "$cert" && -s "$key" ]]; then
    if [[ "$PUBLIC_HOST" =~ ^[0-9]+(\.[0-9]+){3}$ ]]; then openssl x509 -in "$cert" -noout -checkip "$PUBLIC_HOST" >/dev/null 2>&1 && valid=1 || true
    else openssl x509 -in "$cert" -noout -checkhost "$PUBLIC_HOST" >/dev/null 2>&1 && valid=1 || true
    fi
  fi
  if ((valid == 0)); then
    rm -f "$cert" "$key"
    openssl req -x509 -newkey rsa:3072 -sha256 -nodes -days 825 -keyout "$key" -out "$cert" \
      -subj "/CN=${PUBLIC_HOST}" -addext "subjectAltName=${PUBLIC_SAN},DNS:localhost,IP:127.0.0.1" >/dev/null 2>&1
  fi
  chown "$owner:$group" "$cert" "$key"; chmod 644 "$cert"; chmod 640 "$key"
}
