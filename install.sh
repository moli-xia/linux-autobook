install -d -m 755 "$INSTALL_DIR"
if [[ "$(readlink -f "$SOURCE_DIR")" != "$(readlink -f "$INSTALL_DIR")" ]]; then
  tar -C "$SOURCE_DIR" --exclude=.git --exclude=.env --exclude=runtime --exclude=password.txt --exclude=.venv --exclude=__pycache__ -cf - . | tar -C "$INSTALL_DIR" -xf -
