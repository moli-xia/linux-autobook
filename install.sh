    if [[ "$ROLE" == "all" ]]; then
      set_env "$CONFIG_DIR/worker.env" BAIDU_GATEWAY_URL "https://${DOMAIN}:8765"
      set_env "$CONFIG_DIR/worker.env" BAIDU_GATEWAY_CA_FILE ""
    fi
  else
    echo "WARNING: Let's Encrypt issuance failed. Keeping a self-signed certificate." >&2
    echo "Check that $DOMAIN resolves here and inbound port 80 is open, then rerun the installer." >&2
    if [[ "$ROLE" == "all" ]]; then
      set_env "$CONFIG_DIR/worker.env" BAIDU_GATEWAY_URL "https://127.0.0.1:8765"
      set_env "$CONFIG_DIR/worker.env" BAIDU_GATEWAY_CA_FILE "$INSTALL_DIR/runtime/gateway.crt"
    fi
  fi
fi

echo "[6/8] Installing systemd services..."
install_unit() { sed "s|/opt/autobook-linux|$INSTALL_DIR|g" "$1" > "$2"; chmod 644 "$2"; }
install_unit "$INSTALL_DIR/deploy/autobook-admin.service" /etc/systemd/system/autobook-admin.service
if [[ "$ROLE" == "all" || "$ROLE" == "gateway" ]]; then
  install_unit "$INSTALL_DIR/deploy/autobook-gateway.service" /etc/systemd/system/autobook-gateway.service
else
  systemctl disable --now autobook-gateway.service 2>/dev/null || true
  rm -f /etc/systemd/system/autobook-gateway.service
fi
if [[ "$ROLE" == "all" || "$ROLE" == "worker" ]]; then
  install_unit "$INSTALL_DIR/deploy/autobook-worker.service" /etc/systemd/system/autobook-worker.service
else
  systemctl disable --now autobook-worker.service 2>/dev/null || true
  rm -f /etc/systemd/system/autobook-worker.service
fi
systemctl daemon-reload
if [[ "$ROLE" == "all" || "$ROLE" == "gateway" ]]; then systemctl enable autobook-gateway.service >/dev/null; fi
if [[ "$ROLE" == "all" || "$ROLE" == "worker" ]]; then systemctl enable autobook-worker.service >/dev/null; fi
systemctl enable autobook-admin.service >/dev/null
systemctl restart autobook-admin.service
if [[ "$ROLE" == "all" || "$ROLE" == "gateway" ]] && ((WAS_GATEWAY_ACTIVE == 1)); then
  systemctl restart autobook-gateway.service
fi
if [[ "$ROLE" == "all" || "$ROLE" == "worker" ]] && ((WAS_WORKER_ACTIVE == 1)); then
  systemctl restart autobook-worker.service
fi

echo "[7/8] Running tests and service checks..."
cd "$INSTALL_DIR"
"$INSTALL_DIR/.venv/bin/python" -m unittest discover -s tests -q
panel_ready=0
for _ in {1..15}; do
  if curl -kfsS "https://127.0.0.1:${ADMIN_PORT}/health" >/dev/null 2>&1; then panel_ready=1; break; fi
  sleep 1
done
((panel_ready == 1)) || { journalctl -u autobook-admin -n 30 --no-pager; echo "Admin panel failed to become ready" >&2; exit 1; }

echo "[8/8] Updating firewall rules when UFW is active..."
if command -v ufw >/dev/null 2>&1 && ufw status | grep -q '^Status: active'; then
  ufw allow "${ADMIN_PORT}/tcp" comment 'linux-autobook admin' >/dev/null
  if [[ "$ROLE" == "all" || "$ROLE" == "gateway" ]]; then ufw allow 8765/tcp comment 'linux-autobook gateway' >/dev/null; fi
fi

if [[ "$PUBLIC_HOST" == *:* ]]; then PANEL_URL="https://[${PUBLIC_HOST}]:${ADMIN_PORT}/"; else PANEL_URL="https://${PUBLIC_HOST}:${ADMIN_PORT}/"; fi
TLS_MODE="$(sed -n 's/^TLS_MODE=//p' "$CONFIG_DIR/install.env" | tr -d "'")"
echo
